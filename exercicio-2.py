# Objetivo: Somar e subtrair dois números fornecidos pelo usuário.

# Pedindo os números ao usuário
n1 = int(input("Digite o primeiro número: "))
n2 = int(input("Digite o segundo número: "))

# Realizando as operações de soma 
soma = n1 + n2
# Realizando as operações de subtração
subtracao = n1 - n2

# Exibindo o resultado da soma
print("A soma dos números é:", soma)
# Exibindo o resultado da subtração
print("A subtração dos números é:", subtracao)